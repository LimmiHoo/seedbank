def rolling_average(values, window):
    if window <= 0:
        raise ValueError("окно должно быть положительным")
    if not values:
        return []
    result = []
    for i in range(len(values)):
        start = max(0, i - window + 1)
        chunk = values[start:i + 1]
        result.append(sum(chunk) / len(chunk))
    return result


def seed_viability_trend(records, window=7):
    values = [record["всхожесть"] for record in records if "всхожесть" in record]
    return rolling_average(values, window)


